/** Fast lookup by station id. */
export const STATION_BY_ID: ReadonlyMap<string, ClimateStationRecord> = new Map(
  CLIMATE_STATIONS.map((station) => [station.location.id, station]),
);

/** Distinct countries present in the database, sorted. */
export const AVAILABLE_COUNTRIES: string[] = Array.from(
  new Set(CLIMATE_STATIONS.map((s) => s.location.country)),
).sort();

/** Cities in a given country. */
export function citiesInCountry(country: string): ClimateStationRecord[] {
  return CLIMATE_STATIONS.filter((s) => s.location.country === country);
}

/** Distinct states/regions within a country, sorted. */
export function statesInCountry(country: string): string[] {
  return Array.from(new Set(citiesInCountry(country).map((s) => s.location.state))).sort();
}

/**
 * Nearest station to an arbitrary coordinate — the fallback for map clicks.
 */
export function nearestStation(
  latitude: number,
  longitude: number,
): { station: ClimateStationRecord; distanceKm: number } {
  const toRad = (d: number) => (d * Math.PI) / 180;
  const distance = (aLat: number, aLon: number, bLat: number, bLon: number) => {
    const dLat = toRad(bLat - aLat);
    const dLon = toRad(bLon - aLon);
    const h =
      Math.sin(dLat / 2) ** 2 +
      Math.cos(toRad(aLat)) * Math.cos(toRad(bLat)) * Math.sin(dLon / 2) ** 2;
    return 2 * 6371 * Math.asin(Math.min(1, Math.sqrt(h)));
  };

  let best = CLIMATE_STATIONS[0]!;
  let bestDistance = Number.POSITIVE_INFINITY;

  for (const station of CLIMATE_STATIONS) {
    const d = distance(latitude, longitude, station.location.latitude, station.location.longitude);
    if (d < bestDistance) {
      bestDistance = d;
      best = station;
    }
  }

  return { station: best, distanceKm: bestDistance };
}

