/**
 * Offline climatology database.
 *
 * Each station holds 12 months of climatological normals: mean / mean-daily-max
 * / mean-daily-min dry-bulb temperature, relative humidity, wind speed and
 * prevailing direction, daily global horizontal irradiation, monthly rainfall
 * and mean daily sunshine hours.
 *
 * These are representative long-term normals compiled for prototype use. They are
 * clearly labelled as a database source in the UI so they are never presented as
 * live measurements. Replace `climate/climateService.ts`'s provider to pull live
 * data instead — the rest of the pipeline is unchanged.
 */

import type { ClimateStationRecord, ClimateZone, MonthlyClimate } from '@/types';

/** Compact monthly tuple: [avg, max, min, rh, windSpeed, windDir, solar, rain, sun]. */
type MonthTuple = [
  number, number, number, number, number, number, number, number, number,
];

interface StationSeed {
  id: string;
  city: string;
  state: string;
  country: string;
  latitude: number;
  longitude: number;
  elevation: number;
  climateType: string;
  climateZone: ClimateZone;
  /** January first. */
  months: MonthTuple[];
}

const MONTH_KEYS = [
  'avgTemp', 'maxTemp', 'minTemp', 'humidity', 'windSpeed',
  'windDirection', 'solarRadiation', 'rainfall', 'sunshineHours',
] as const;

function toMonthly(months: MonthTuple[]): MonthlyClimate[] {
  return months.map((tuple, index) => {
    const record = { month: index } as MonthlyClimate;
    MONTH_KEYS.forEach((key, i) => {
      // Tuple length is validated by construction; the cast keeps the mapper terse.
      (record as unknown as Record<string, number>)[key] = tuple[i] ?? 0;
    });
    return record;
  });
}

